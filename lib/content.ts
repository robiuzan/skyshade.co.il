export interface FaqPair {
  q: string;
  a: string;
}

/**
 * A deep-dive block on a service page. Optional and deliberately NOT templated across the six
 * services: measured 2026-08-25, any two service pages shared 57% of their 8-grams, so the fix
 * is substance that only makes sense on ONE page — not another shared section on all of them.
 *
 * Everything written here must be material, engineering or decision knowledge. No prices, no
 * warranty terms, no capability the site does not already claim elsewhere (docs/evidence-register.md).
 */
export interface ServiceSection {
  heading: string;
  /** Optional lead paragraph under the heading. */
  body?: string;
  /** Optional term/explanation list. */
  items?: { term: string; text: string }[];
  /** Optional trailing link — usually to the guide that owns this question. */
  link?: { href: string; label: string };
}

export interface ServiceDetail {
  /** Longer "about" paragraph shown on the service page. */
  about: string;
  /** Key benefits / selling points. */
  benefits: string[];
  /** Deep-dive sections — per-service substance, deliberately different on each page. */
  sections?: ServiceSection[];
  /** Per-service FAQ (3–5 Q&A). */
  faqs: FaqPair[];
}

